/* ============================================================
   CURRENT LANGUAGE STATE
============================================================ */
let currentLang = "fr";

/* ============================================================
   APPLY TRANSLATIONS
============================================================ */
function applyLang(lang) {
  const t = translations[lang];
  if (!t) return;
  currentLang = lang;

  // Update <html lang> attribute
  document.documentElement.lang = lang;

  // Update all elements that carry a data-i18n attribute
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (t[key] !== undefined) {
      el.innerHTML = t[key];
    }
  });

  // Update all placeholders (data-i18n-placeholder)
  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (t[key] !== undefined) {
      el.placeholder = t[key];
    }
  });

  // Toggle active state on language buttons
  document.querySelectorAll(".lang-btn").forEach(btn => {
    btn.classList.toggle("active", btn.dataset.lang === lang);
  });

  // Persist choice
  try { localStorage.setItem("pkd_lang", lang); } catch(e) {}
}

/* ============================================================
   LANGUAGE BUTTON WIRING
============================================================ */
function initLangToggle() {
  document.querySelectorAll(".lang-btn").forEach(btn => {
    btn.addEventListener("click", () => applyLang(btn.dataset.lang));
  });

  // Restore saved preference
  let saved = "fr";
  try { saved = localStorage.getItem("pkd_lang") || "fr"; } catch(e) {}
  applyLang(saved);
}

/* ============================================================
   CONTACT FORM
============================================================ */
function initContactForm() {
  const form = document.getElementById("contact-form");
  if (!form) return;

  form.addEventListener("submit", e => {
    e.preventDefault();
    const t = translations[currentLang];
    const btn = form.querySelector(".btn-submit");
    btn.disabled = true;
    btn.textContent = "✓ " + (t.form_success || "Message sent!");
    btn.style.background = "#78c882";
    btn.style.color = "#0d0d0d";
    setTimeout(() => {
      btn.disabled = false;
      btn.innerHTML = t.form_send;
      btn.style.background = "";
      btn.style.color = "";
      form.reset();
    }, 3500);
  });
}

/* ============================================================
   SMOOTH ACTIVE NAV HIGHLIGHT
============================================================ */
function initActiveNav() {
  const sections = document.querySelectorAll("section[id]");
  const links    = document.querySelectorAll(".nav-links a");

  const observer = new IntersectionObserver(entries => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        links.forEach(l => {
          l.style.color = "";
          if (l.getAttribute("href") === "#" + entry.target.id) {
            l.style.color = "var(--accent)";
          }
        });
      }
    });
  }, { rootMargin: "-40% 0px -55% 0px" });

  sections.forEach(s => observer.observe(s));
}

/* ============================================================
   SCROLL-REVEAL (lightweight, no lib needed)
============================================================ */
function initScrollReveal() {
  const style = document.createElement("style");
  style.textContent = `
    .reveal { opacity: 0; transform: translateY(24px); transition: opacity .55s ease, transform .55s ease; }
    .reveal.visible { opacity: 1; transform: none; }
  `;
  document.head.appendChild(style);

  const targets = document.querySelectorAll(
    ".tl-item, .project-card, .skill-card, .edu-card, .stat, .contact-link-item"
  );
  targets.forEach(el => el.classList.add("reveal"));

  const io = new IntersectionObserver(entries => {
    entries.forEach((entry, i) => {
      if (entry.isIntersecting) {
        setTimeout(() => entry.target.classList.add("visible"), i * 60);
        io.unobserve(entry.target);
      }
    });
  }, { threshold: 0.1 });

  targets.forEach(el => io.observe(el));
}

/* ============================================================
   BOOT
============================================================ */
document.addEventListener("DOMContentLoaded", () => {
  initLangToggle();
  initContactForm();
  initActiveNav();
  initScrollReveal();
});
